export function SessionAgentIcon({
  runtime,
  runtimeType,
}: {
  runtime: string
  runtimeType?: string
}) {
  const type = (runtimeType?.trim() || runtime)
    .toLowerCase()
    .replace(/[\s_-]/g, '')
  const agent =
    type === 'codex'
      ? 'codex'
      : type === 'claude' || type === 'claudecode'
        ? 'claude'
        : type === 'dsh' || type === 'deepseek' || type === 'deepseekharness'
          ? 'deepseek'
          : null

  if (!agent)
    return <Bot aria-label={runtime} role="img" data-icon="inline-start" />

  const icon = agentIcons[agent]
  const label =
    agent === 'codex'
      ? 'Codex'
      : agent === 'claude'
        ? 'Claude Code'
        : 'DeepSeek Harness'

  return (
    <svg
      viewBox={icon.viewBox}
      fill="currentColor"
      role="img"
      aria-label={label}
      data-icon="inline-start"
    >
      <path d={icon.path} />
    </svg>
  )
}
