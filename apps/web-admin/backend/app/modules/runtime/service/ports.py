"""运行领域端口；领域层不依赖数据库、HTTP 或受管进程实现。"""

from __future__ import annotations

from collections.abc import AsyncIterator, Awaitable, Callable
from typing import Protocol

from app.modules.runtime.entity.bo.values import Fields, Json


class Ownership(Protocol):
    """独占所有权；失效后必须停止执行，释放在进程退出之后。"""

    async def check(self) -> bool: ...
    async def release(self) -> None: ...


class OwnershipProvider(Protocol):
    """为一个用户原子取得运行租约，不用替换锁名绕过争用。"""

    async def acquire(self, owner: str) -> Ownership: ...


class ProjectionSink(Protocol):
    """连接器只依赖持久提交，不获得消息写入或所有权管理能力。"""

    async def commit(self, owner: str, batch: Fields) -> Fields: ...


class ProjectionStore(ProjectionSink, Protocol):
    """投影与操作收据持久端口；成功返回后才能确认引擎批次。"""

    async def events(self, owner: str, after: int = 0) -> list[Fields]: ...
    async def replay(self, owner: str, identifier: str, digest: str) -> tuple[bool, Json]: ...
    async def reserve(self, owner: str, identifier: str, digest: str) -> tuple[bool, Json]: ...
    async def settle(self, owner: str, identifier: str, result: Json) -> None: ...
    async def fence(self, owner: str) -> Fields | None: ...
    async def claim_execution(self, owner: str, generation: str, machine: str) -> None: ...
    async def attach_execution(self, owner: str, generation: str, pid: int) -> None: ...
    async def release_execution(self, owner: str, generation: str) -> None: ...


class ModelProvider(Protocol):
    """受限模型网关；供应商密钥永不进入 Host 的环境变量。"""

    async def catalog(self, owner: str) -> Fields: ...
    def stream(self, owner: str, path: str, body: Fields) -> AsyncIterator[bytes]: ...


Authorize = Callable[[str], Awaitable[None]]
ToolCall = Callable[[str, Fields], Awaitable[Json]]


class RuntimeRunner(Protocol):
    """应用层只依赖运行能力端口，进程、协议和租约由外层实现。"""

    def status(self, owner: str) -> Fields: ...
    async def is_ready(self) -> bool: ...
    async def prepare(self, owner: str) -> Fields: ...
    async def stop(self, owner: str) -> None: ...
    async def call(self, owner: str, method: str, params: Fields) -> Json: ...
    async def events(self, owner: str, after: int) -> list[Fields]: ...
    async def close(self) -> None: ...


class RuntimeConfigurator(Protocol):
    """受信资源装配端口，与普通消息执行接口分离。"""

    async def install_tool(self, owner: str, tool: Fields) -> None: ...
    async def install_preset(self, owner: str, preset: Fields) -> None: ...
