"""身份事务端口，应用用例只依赖实体与这里的接口。"""

from contextlib import AbstractAsyncContextManager
from datetime import datetime
from typing import Protocol

from app.modules.identity.entity.bo.models import LoginSession, Role, User
from app.modules.identity.entity.bo.oauth import OAuthGrant


class IdentityTransaction(Protocol):
    """同一短事务中的账号/角色/会话与审计操作。"""

    async def lock(self) -> None: ...
    async def users(self) -> list[User]: ...
    async def user(self, user_id: str) -> User | None: ...
    async def find_user(self, identifier: str) -> User | None: ...
    async def save_user(self, user: User) -> None: ...
    async def roles(self) -> list[Role]: ...
    async def save_role(self, role: Role) -> None: ...
    async def delete_role(self, role_id: str) -> None: ...
    async def session(self, session_id: str, *, lock: bool = False) -> LoginSession | None: ...
    async def sessions(self, user_id: str) -> list[LoginSession]: ...
    async def save_session(self, session: LoginSession) -> None: ...
    async def touch_session(self, session_id: str, now: datetime) -> None: ...
    async def audit(
        self, actor: str | None, action: str, target: str, detail: dict[str, object]
    ) -> None: ...


class IdentityRepository(Protocol):
    """由基础设施创建事务，提交失败不能返回业务成功。"""

    def transaction(self) -> AbstractAsyncContextManager[IdentityTransaction]: ...


class IdentitySecurity(Protocol):
    """密码和令牌的加密端口，应用层不依赖具体加密库。"""

    async def hash_password(
        self, password: str | None, verifier: str | None, salt: str | None
    ) -> str: ...
    async def verify(self, stored: str, password: str | None, verifier: str | None) -> bool: ...
    def issue(self, user_id: str, session_id: str, version: int) -> str: ...
    def decode(self, token: str) -> dict[str, object]: ...
    def hash_token(self, value: str) -> str: ...


class OAuthTransaction(Protocol):
    """单次授权码行锁与持久数据操作。"""

    async def save(self, grant: OAuthGrant) -> None: ...
    async def read(self, code_hash: str, lock: bool = False) -> OAuthGrant | None: ...


class OAuthRepository(Protocol):
    """服务持有事务上下文，DAO 不决定有效期或授权结果。"""

    def transaction(self) -> AbstractAsyncContextManager[OAuthTransaction]: ...
